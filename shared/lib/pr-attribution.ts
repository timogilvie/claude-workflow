export type AttributionSignal =
  | 'firstPartyRoute'
  | 'botAuthor'
  | 'coAuthoredBy'
  | 'branchPrefix'
  | 'label'
  | 'commitSignature';

export type AttributionConfidence = 'verified' | 'strong' | 'weak';

export type HarnessId =
  | 'github-copilot'
  | 'claude-code'
  | 'openai-codex'
  | 'cursor'
  | 'aider'
  | 'devin'
  | 'openhands'
  | 'sweep'
  | 'codegen'
  | 'swe-agent'
  | 'wavemill'
  | string; // allow extensibility for custom harnessess

export interface PullRequestInput {
  number: number;
  title?: string;
  authorLogin: string | null;
  authorType: string | null;
  headRef: string | null;
  labels: string[];
  mergedAt: string;
  commitMessages: string[];
  body?: string;
  headSha?: string;
}

export interface AttributionEvidence {
  signal: AttributionSignal;
  dimension: 'agentAuthored' | 'harness' | 'model';
  value: string; // raw matched value (login, trailer, prefix, …)
  rule: string; // e.g. 'branch-prefix:codex/', 'first-party:executed-route'
  confidence: AttributionConfidence;
}

export interface DimensionAttribution {
  value: string | 'unknown'; // agentAuthored uses 'agent' | 'unknown'
  confidence: AttributionConfidence | null; // null iff value === 'unknown'
  conflict: boolean; // same-tier disagreement collapsed to unknown
  evidence: AttributionEvidence[]; // all contributing evidence, kept even on unknown
}

export interface PrAttribution {
  number: number;
  signals: AttributionSignal[]; // which signals fired at all (coverage-by-signal)
  agentAuthored: DimensionAttribution;
  harness: DimensionAttribution;
  model: DimensionAttribution;
}

export interface SignalEvidence {
  pr: number;
  signal: AttributionSignal;
  value: string;
  rule: string;
}

export interface AttributedPullRequest {
  number: number;
  signals: AttributionSignal[];
  evidence: SignalEvidence[];
}

export interface AttributionSummary {
  repo: string;
  sampledMergedPrs: number;
  signalCounts: Record<AttributionSignal, number>;
  unionCount: number;
  unattributedCount: number;
  coverage: Record<AttributionSignal | 'union' | 'unattributed', number>;
  pullRequests: AttributedPullRequest[];
}

