interface HeuristicSignalWithConfidence {
  signal: AttributionSignal;
  dimension: 'agentAuthored' | 'harness' | 'model';
  value: string;
  mapping: SignatureMapping;
  confidence: AttributionConfidence;
  order: number; // for precedence comparison within tier
}

function collectDimensionEvidence(
  pr: PullRequestInput,
  disabledSignals: Set<AttributionSignal> = new Set(),
): HeuristicSignalWithConfidence[] {
  const evidence: HeuristicSignalWithConfidence[] = [];
  const authorLogin = pr.authorLogin ? normalized(pr.authorLogin) : '';
  const authorType = pr.authorType ? normalized(pr.authorType) : '';

  // botAuthor detection (precedence: 4)
  if (!disabledSignals.has('botAuthor')) {
    let match: SignatureMapping | null = null;
    let rawValue = '';

    if (authorLogin && BOT_LOGIN_MAPPING[authorLogin]) {
      match = BOT_LOGIN_MAPPING[authorLogin];
      rawValue = pr.authorLogin ?? '';
    } else if (authorType === 'bot') {
      const stripped = authorLogin.replace(/\[bot\]$/, '');
      if (BOT_LOGIN_MAPPING[stripped]) {
        match = BOT_LOGIN_MAPPING[stripped];
        rawValue = pr.authorLogin ?? '';
      }
    }

    if (match) {
      if (match.agentAuthored) {
        evidence.push({
          signal: 'botAuthor',
          dimension: 'agentAuthored',
          value: rawValue,
          mapping: match,
          confidence: 'strong',
          order: 4,
        });
      }
      if (match.harness) {
        evidence.push({
          signal: 'botAuthor',
          dimension: 'harness',
          value: rawValue,
          mapping: match,
          confidence: 'strong',
          order: 4,
        });
      }
    }
  }

  // commitSignature detection (precedence: 5)
  if (!disabledSignals.has('commitSignature')) {
    for (const message of pr.commitMessages) {
      const messageText = normalized(message);
      for (const [fragment, mapping] of Object.entries(COMMIT_SIGNATURE_MAPPING)) {
        if (messageText.includes(fragment)) {
          if (mapping.agentAuthored) {
            evidence.push({
              signal: 'commitSignature',
              dimension: 'agentAuthored',
              value: fragment,
              mapping,
              confidence: 'strong',
              order: 5,
            });
          }
          if (mapping.harness) {
            evidence.push({
              signal: 'commitSignature',
              dimension: 'harness',
              value: fragment,
              mapping,
              confidence: 'strong',
              order: 5,
            });
          }
          break; // one match per message
        }
      }
    }
  }

  // coAuthoredBy detection (precedence: 6)
  if (!disabledSignals.has('coAuthoredBy')) {
    let foundModelTrailer = false; // Only use first model-bearing trailer globally
    for (const message of pr.commitMessages) {
      for (const trailer of extractCoAuthorTrailers(message)) {
        const trailerNorm = normalized(trailer);
        let foundMatch = false;

        // Check for model-bearing trailers first (but only use the first one overall)
        if (!foundModelTrailer) {
          for (const [trailerPattern, modelId] of Object.entries(MODEL_BEARING_TRAILERS)) {
            if (trailerNorm.includes(trailerPattern)) {
              evidence.push({
                signal: 'coAuthoredBy',
                dimension: 'agentAuthored',
                value: trailer,
                mapping: { agentAuthored: 'agent' },
                confidence: 'strong',
                order: 6,
              });
              evidence.push({
                signal: 'coAuthoredBy',
                dimension: 'harness',
                value: trailer,
                mapping: { agentAuthored: 'agent', harness: 'claude-code' }, // assume claude-code for model trailer
                confidence: 'strong',
                order: 6,
              });
              evidence.push({
                signal: 'coAuthoredBy',
                dimension: 'model',
                value: trailer,
                mapping: { agentAuthored: 'agent', model: modelId },
                confidence: 'strong',
                order: 6,
              });
              foundMatch = true;
              foundModelTrailer = true; // Don't use any more model trailers
              break;
            }
          }
        }

        // If no model trailer match, check for generic agent fragments (harness only)
        if (!foundMatch) {
          const matched = DETECTOR_SIGNATURES.coAuthorFragments.find((fragment) =>
            trailerNorm.includes(fragment),
          );
          if (matched) {
            const harnessMap: Record<string, HarnessId> = {
              'claude': 'claude-code',
              'anthropic': 'claude-code',
              'copilot': 'github-copilot',
              'codex': 'openai-codex',
              'openai': 'openai-codex',
              'cursor': 'cursor',
              'aider': 'aider',
              'devin': 'devin',
              'openhands': 'openhands',
              'sweep ai': 'sweep',
              'swe-agent': 'swe-agent',
              'codegen': 'codegen',
            };

            evidence.push({
              signal: 'coAuthoredBy',
              dimension: 'agentAuthored',
              value: trailer,
              mapping: { agentAuthored: 'agent' },
              confidence: 'strong',
              order: 6,
            });

            if (harnessMap[matched]) {
              evidence.push({
                signal: 'coAuthoredBy',
                dimension: 'harness',
                value: trailer,
                mapping: { agentAuthored: 'agent', harness: harnessMap[matched] },
                confidence: 'strong',
                order: 6,
              });
            }
          }
        }
      }
    }
  }

  // branchPrefix detection (precedence: 7)
  if (!disabledSignals.has('branchPrefix') && pr.headRef) {
    const headRef = normalized(pr.headRef);
    for (const [prefix, mapping] of Object.entries(BRANCH_PREFIX_MAPPING)) {
      if (headRef.startsWith(prefix)) {
        if (mapping.agentAuthored) {
          evidence.push({
            signal: 'branchPrefix',
            dimension: 'agentAuthored',
            value: pr.headRef,
            mapping,
            confidence: 'weak',
            order: 7,
          });
        }
        if (mapping.harness) {
          evidence.push({
            signal: 'branchPrefix',
            dimension: 'harness',
            value: pr.headRef,
            mapping,
            confidence: 'weak',
            order: 7,
          });
        }
        break; // one match per branch
      }
    }
  }

  // label detection (precedence: 8)
  if (!disabledSignals.has('label')) {
    for (const label of pr.labels) {
      const labelName = normalized(label);
      const mapping = LABEL_MAPPING[labelName];
      if (mapping) {
        if (mapping.agentAuthored) {
          evidence.push({
            signal: 'label',
            dimension: 'agentAuthored',
            value: label,
            mapping,
            confidence: 'weak',
            order: 8,
          });
        }
        if (mapping.harness) {
          evidence.push({
            signal: 'label',
            dimension: 'harness',
            value: label,
            mapping,
            confidence: 'weak',
            order: 8,
          });
        }
      }
    }
  }

  return evidence;
}

function resolveDimensionFromEvidence(
  evidence: HeuristicSignalWithConfidence[],
  dimension: 'agentAuthored' | 'harness' | 'model',
  disabledSignals: Set<AttributionSignal>,
): DimensionAttribution {
  // Filter to this dimension
  const dimEvidence = evidence.filter((e) => e.dimension === dimension && !disabledSignals.has(e.signal));

  if (dimEvidence.length === 0) {
    return {
      value: 'unknown',
      confidence: null,
      conflict: false,
      evidence: [],
    };
  }

  // Group by confidence tier
  const byConfidence: Record<AttributionConfidence, HeuristicSignalWithConfidence[]> = {
    verified: [],
    strong: [],
    weak: [],
  };

  for (const e of dimEvidence) {
    byConfidence[e.confidence].push(e);
  }

  // Highest tier wins (verified > strong > weak)
  for (const tier of ['verified', 'strong', 'weak'] as const) {
    if (byConfidence[tier].length === 0) continue;

    const tierEvidence = byConfidence[tier];

    // Within a tier, sort by signal precedence (lower order number = higher precedence)
    tierEvidence.sort((a, b) => a.order - b.order);

    const topOrder = tierEvidence[0].order;
    const topCandidates = tierEvidence.filter((e) => e.order === topOrder);

    // Extract values to check for conflicts
    const extractValue = (e: HeuristicSignalWithConfidence): string => {
      if (dimension === 'agentAuthored') {
        return e.mapping.agentAuthored ?? 'unknown';
      } else if (dimension === 'harness') {
        return e.mapping.harness ?? 'unknown';
      } else if (dimension === 'model') {
        return e.mapping.model ?? 'unknown';
      }
      return 'unknown';
    };

    // agentAuthored never conflicts (all "agent" values)
    if (dimension === 'agentAuthored') {
      return {
        value: 'agent',
        confidence: tier,
        conflict: false,
        // Include all evidence from the winning tier (all agree on "agent")
        evidence: tierEvidence.map((e) => ({
          signal: e.signal,
          dimension,
          value: e.value,
          rule: `${e.signal}:${e.value}`,
          confidence: tier,
        })),
      };
    }

    // Check for distinct values at top precedence
    const uniqueValues = new Set<string>();
    const byValue = new Map<string, HeuristicSignalWithConfidence[]>();

    for (const e of topCandidates) {
      const value = extractValue(e);
      uniqueValues.add(value);
      if (!byValue.has(value)) {
        byValue.set(value, []);
      }
      byValue.get(value)!.push(e);
    }

    if (uniqueValues.size === 1) {
      // No conflict: only include winning tier evidence
      const value = [...uniqueValues][0];
      return {
        value: value === 'unknown' ? 'unknown' : value,
        confidence: value === 'unknown' ? null : tier,
        conflict: false,
        evidence: topCandidates.map((e) => ({
          signal: e.signal,
          dimension,
          value: e.value,
          rule: `${e.signal}:${e.value}`,
          confidence: tier,
        })),
      };
    }

    // Conflict: multiple distinct values at same tier
    // Include ALL evidence from this tier (not just top candidates) for full transparency
    return {
      value: 'unknown',
      confidence: null,
      conflict: true,
      evidence: tierEvidence.map((e) => ({
        signal: e.signal,
        dimension,
        value: e.value,
        rule: `${e.signal}:${e.value}`,
        confidence: tier,
      })),
    };
  }

  return {
    value: 'unknown',
    confidence: null,
    conflict: false,
    evidence: [],
  };
}

interface ExecutedRouteStatus {
  planner?: ExecutedRoleRoute;
  coder?: ExecutedRoleRoute;
  reviewer?: ExecutedRoleRoute;
}

interface ExecutedRoleRoute {
  model: string;
  adapter: string;
  status: 'executed' | 'inherited' | 'not_run' | 'unknown';
  evidence?: string;
  headSha?: string;
}

interface ExecutedRouteExtraction {
  valid: boolean;
  error?: string;
  status?: ExecutedRouteStatus;
  raw?: string;
}

function lentientlyExtractWavemillMeta(body: string | undefined): string | null {
  if (!body) return null;

  // Last block wins (matches extractMetadataBlock semantics)
  let block: string | null = null;
  const regex = /<!-- wavemill-meta\n([\s\S]*?)\n-->/g;

  for (const match of body.matchAll(regex)) {
    block = match[1] ?? '';
  }

  return block;
}

function validateExecutedRoute(route: unknown, headSha: string | undefined): ExecutedRouteExtraction {
  if (typeof route !== 'object' || route === null) {
    return { valid: false, error: 'not-an-object' };
  }

  const status: ExecutedRouteStatus = {};
  const roles: Array<'planner' | 'coder' | 'reviewer'> = ['planner', 'coder', 'reviewer'];

  for (const role of roles) {
    const entry = (route as Record<string, unknown>)[role];
    if (!entry) continue;

    if (typeof entry !== 'object' || entry === null) {
      return { valid: false, error: `role-${role}-not-object` };
    }

    const e = entry as Record<string, unknown>;
    const model = e.model;
    const adapter = e.adapter;
    const stat = e.status;

    if (typeof model !== 'string' || !model) {
      return { valid: false, error: `role-${role}-missing-model` };
    }
    if (typeof adapter !== 'string' || !adapter) {
      return { valid: false, error: `role-${role}-missing-adapter` };
    }
    if (!['executed', 'inherited', 'not_run', 'unknown'].includes(stat as string)) {
      return { valid: false, error: `role-${role}-invalid-status` };
    }

    // If status is 'executed', check head SHA freshness
    if (stat === 'executed') {
      const roleHeadSha = e.headSha;
      if (roleHeadSha && typeof roleHeadSha === 'string' && headSha && roleHeadSha !== headSha) {
        // Stale: head SHA doesn't match PR head
        status[role as 'planner' | 'coder' | 'reviewer'] = {
          model,
          adapter,
          status: 'unknown', // Treat stale as unknown
          evidence: 'stale-head-sha',
          headSha: roleHeadSha,
        };
        continue;
      }
    }

    status[role as 'planner' | 'coder' | 'reviewer'] = {
      model,
      adapter,
      status: stat as 'executed' | 'inherited' | 'not_run' | 'unknown',
      headSha: typeof e.headSha === 'string' ? e.headSha : undefined,
    };
  }

  return { valid: true, status, raw: JSON.stringify(route) };
}

function extractFirstPartyRoute(
  pr: PullRequestInput,
  disabledSignals: Set<AttributionSignal>,
): HeuristicSignalWithConfidence[] {
  if (disabledSignals.has('firstPartyRoute') || !pr.body || !pr.headSha) {
    return [];
  }

  const evidence: HeuristicSignalWithConfidence[] = [];
  const block = lentientlyExtractWavemillMeta(pr.body);
  if (!block) return [];

  let routeSchema: string | null = null;
  let executedRouteJson: string | null = null;

  for (const line of block.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    const match = trimmed.match(/^route_schema:\s*(.+)$/);
    if (match) {
      routeSchema = match[1].trim();
      continue;
    }

    const match2 = trimmed.match(/^executed_route:\s*(.+)$/);
    if (match2) {
      executedRouteJson = match2[1].trim();
      continue;
    }
  }

  if (!routeSchema || routeSchema !== '1') {
    return []; // Wrong or missing schema version
  }

  if (!executedRouteJson) {
    return []; // Missing executed_route
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(executedRouteJson);
  } catch {
    // Malformed JSON
    return [];
  }

  const extraction = validateExecutedRoute(parsed, pr.headSha);
  if (!extraction.valid || !extraction.status) {
    return [];
  }

  // Only use executed coder role with valid head SHA
  const coderRoute = extraction.status.coder;
  if (coderRoute && coderRoute.status === 'executed') {
    evidence.push({
      signal: 'firstPartyRoute',
      dimension: 'agentAuthored',
      value: 'agent',
      mapping: { agentAuthored: 'agent' },
      confidence: 'verified',
      order: 1, // Highest precedence
    });

    evidence.push({
      signal: 'firstPartyRoute',
      dimension: 'harness',
      value: coderRoute.adapter,
      mapping: { agentAuthored: 'agent', harness: coderRoute.adapter as HarnessId },
      confidence: 'verified',
      order: 1,
    });

    evidence.push({
      signal: 'firstPartyRoute',
      dimension: 'model',
      value: coderRoute.model,
      mapping: { agentAuthored: 'agent', model: coderRoute.model },
      confidence: 'verified',
      order: 1,
    });
  }

  return evidence;
}

export function attributePullRequest(
  pr: PullRequestInput,
  disabledSignals: Set<AttributionSignal> = new Set(),
): PrAttribution {
  // Phase 3: Extract first-party route (highest precedence)
  const firstPartyEvidence = extractFirstPartyRoute(pr, disabledSignals);

  // Collect all heuristic evidence (Phase 2)
  const heuristicEvidence = collectDimensionEvidence(pr, disabledSignals);

  // Combine evidence: first-party takes absolute precedence
  const allEvidence = [...firstPartyEvidence, ...heuristicEvidence];

  // Resolve each dimension independently
  const agentAuthored = resolveDimensionFromEvidence(allEvidence, 'agentAuthored', disabledSignals);
  const harness = resolveDimensionFromEvidence(allEvidence, 'harness', disabledSignals);
  const model = resolveDimensionFromEvidence(allEvidence, 'model', disabledSignals);

  // Extract unique signals that fired (including firstPartyRoute)
  const signals = new Set<AttributionSignal>(
    allEvidence.map((e) => e.signal).filter((s) => !disabledSignals.has(s)),
  );

  return {
    number: pr.number,
    signals: Array.from(signals),
    agentAuthored,
    harness,
    model,
  };
}
